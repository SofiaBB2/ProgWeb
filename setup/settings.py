def _read_secret(secret_id):
    project_id = os.environ.get('GOOGLE_CLOUD_PROJECT')
    if not project_id or not secret_id or secret_id.startswith('REPLACE_'):
        raise ImproperlyConfigured('Configure o projeto e os IDs dos segredos do Google Cloud.')

    from google.cloud import secretmanager

    client = secretmanager.SecretManagerServiceClient()
    response = client.access_secret_version(
        request={'name': f'projects/{project_id}/secrets/{secret_id}/versions/latest'}
    )
    return response.payload.data.decode('utf-8')


def _required_secret_id(variable_name):
    secret_id = os.environ.get(variable_name, '')
    if not secret_id:
        raise ImproperlyConfigured(f'A variável {variable_name} é obrigatória no App Engine.')
    return secret_id


